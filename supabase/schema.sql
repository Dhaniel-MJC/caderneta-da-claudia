-- supabase/schema.sql — Caderneta da Cláudia no Supabase
-- Versão do ../schema.sql adaptada ao Supabase Auth:
--   * a pessoa é identificada por user_id (uuid de auth.users), e não mais por usuario_id inteiro;
--   * a senha fica no Supabase Auth (sem senha_hash aqui);
--   * os ids são gerados pelo banco (identity), mas aceitam valor explícito na carga de dados;
--   * user_id tem default auth.uid(): quem insere pelo app não precisa mandar o próprio id.
-- Rode ANTES de supabase/rls.sql, num banco ainda sem essas tabelas.
-- Não há DROP de propósito: se as tabelas já existirem, o script dá erro em vez de apagar dados.

-- R1 — Perfil de cada pessoa (o login em si fica em auth.users)
create table public.usuarios (
    user_id    uuid primary key references auth.users (id) on delete cascade,
    nome       text not null,
    email      text not null unique,
    criado_em  date not null default current_date
);

-- Cria o perfil sozinho quando alguém se cadastra pelo app.
-- O nome vem do campo "Nome" do cadastro (user_metadata.nome); sem ele, usa o começo do e-mail.
create or replace function public.criar_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.usuarios (user_id, nome, email)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'nome'), ''), split_part(new.email, '@', 1)),
    new.email
  );
  return new;
end;
$$;

create trigger ao_criar_usuario
  after insert on auth.users
  for each row execute function public.criar_perfil_usuario();

-- R2 — Contas: cada conta tem exatamente um dono e um saldo inicial (nunca nulo)
create table public.contas (
    conta_id       integer generated by default as identity primary key,
    user_id        uuid          not null default auth.uid() references auth.users (id) on delete cascade,
    nome           text          not null,
    tipo           text          not null check (tipo in ('corrente', 'cartao', 'especie', 'poupanca')),
    saldo_inicial  numeric(10,2) not null,
    data_abertura  date          not null,
    constraint contas_nome_por_usuario unique (user_id, nome),
    -- par de chaves usado pelas FKs compostas (R8: mesmo dono)
    constraint contas_id_usuario_uk unique (conta_id, user_id)
);

-- R3 — Categorias: cor em #RRGGBB, tipo entrada/saída, nome único por pessoa
create table public.categorias (
    categoria_id  integer generated by default as identity primary key,
    user_id       uuid not null default auth.uid() references auth.users (id) on delete cascade,
    nome          text not null,
    tipo          text not null check (tipo in ('entrada', 'saida')),
    cor_hex       text not null check (cor_hex ~ '^#[0-9A-Fa-f]{6}$'),
    constraint categorias_nome_por_usuario unique (user_id, nome),
    constraint categorias_id_usuario_uk unique (categoria_id, user_id)
);

-- R6 — Recorrências: cadastradas uma vez, lançadas pela pessoa a cada mês
create table public.recorrencias (
    recorrencia_id   integer generated by default as identity primary key,
    user_id          uuid          not null default auth.uid() references auth.users (id) on delete cascade,
    conta_id         integer       not null,
    categoria_id     integer       not null,
    descricao        text          not null,
    valor_previsto   numeric(10,2) not null check (valor_previsto > 0),
    dia_do_mes       integer       not null check (dia_do_mes between 1 and 28),
    data_inicio      date          not null,
    data_fim         date          null,
    constraint recorrencias_fim_valido check (data_fim is null or data_fim >= data_inicio),
    constraint recorrencias_id_usuario_uk unique (recorrencia_id, user_id),
    -- R8: conta e categoria precisam pertencer ao mesmo dono da recorrência
    constraint recorrencias_conta_fk
        foreign key (conta_id, user_id) references public.contas (conta_id, user_id),
    constraint recorrencias_categoria_fk
        foreign key (categoria_id, user_id) references public.categorias (categoria_id, user_id)
);

-- R4, R7, R8, R9 — Lançamentos
-- valor sempre positivo: o sinal vem de tipo ('entrada' / 'saida')
create table public.lancamentos (
    lancamento_id    integer       generated by default as identity primary key,
    user_id          uuid          not null default auth.uid() references auth.users (id) on delete cascade,
    conta_id         integer       not null,
    categoria_id     integer       not null,
    recorrencia_id   integer       null,   -- null = lançamento avulso (R7)
    tipo             text          not null check (tipo in ('entrada', 'saida')),
    valor            numeric(10,2) not null check (valor > 0),
    data_lancamento  date          not null,
    descricao        text          null,
    -- R8: conta, categoria e recorrência do mesmo dono do lançamento
    constraint lancamentos_conta_fk
        foreign key (conta_id, user_id) references public.contas (conta_id, user_id),
    -- R9: apagar uma categoria já usada dá erro (NO ACTION, o padrão).
    -- Não usamos RESTRICT porque ele é checado na hora e travaria o apagar em cascata
    -- de uma conta inteira em auth.users; NO ACTION checa no fim do comando.
    constraint lancamentos_categoria_fk
        foreign key (categoria_id, user_id) references public.categorias (categoria_id, user_id),
    constraint lancamentos_recorrencia_fk
        foreign key (recorrencia_id, user_id) references public.recorrencias (recorrencia_id, user_id)
);

-- R11 — Índices para as consultas mais frequentes
create index lancamentos_usuario_data_idx
    on public.lancamentos (user_id, data_lancamento);
create index lancamentos_usuario_categoria_data_idx
    on public.lancamentos (user_id, categoria_id, data_lancamento);
create index lancamentos_conta_idx       on public.lancamentos (conta_id, user_id);
create index lancamentos_categoria_idx   on public.lancamentos (categoria_id, user_id);
create index lancamentos_recorrencia_idx on public.lancamentos (recorrencia_id, user_id);
create index recorrencias_conta_idx      on public.recorrencias (conta_id, user_id);
create index recorrencias_categoria_idx  on public.recorrencias (categoria_id, user_id);

-- R5 — Saldo calculado na hora (não é armazenado)
-- security_invoker = true: a view respeita o RLS de quem consulta.
-- Sem isso, ela rodaria com as permissões do dono e mostraria o saldo de todo mundo.
create view public.saldo_contas
with (security_invoker = true) as
select
    c.conta_id,
    c.user_id,
    c.nome,
    c.saldo_inicial
      + coalesce(sum(case when l.tipo = 'entrada' then l.valor
                          when l.tipo = 'saida'   then -l.valor end), 0) as saldo_atual
from public.contas c
left join public.lancamentos l
       on l.conta_id = c.conta_id
      and l.data_lancamento >= c.data_abertura
group by c.conta_id, c.user_id, c.nome, c.saldo_inicial;
